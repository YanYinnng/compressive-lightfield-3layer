"""Small analytic 3D scenes for honest, independent-view diagnostics.

Targets are ray traced from opaque textured rectangles at known depths, not
generated by the LCD forward model. Neighbour targets are evaluation-only.
"""
import math

import torch

from .core import eye2world_pytroch, synthetic_geometry


def look_at(position):
    return eye2world_pytroch('z', position, delta=torch.zeros(3, device=position.device))


def camera_rays(views, height, width, fov=math.radians(40)):
    y, x = torch.meshgrid(torch.arange(height, device=views.device)+.5,
                          torch.arange(width, device=views.device)+.5, indexing='ij')
    focal = width/(2*math.tan(fov/2))
    local = torch.stack([(x-width/2)/focal, -(y-height/2)/focal, -torch.ones_like(x)], -1)
    directions = torch.einsum('vij,hwj->vhwi', views[:, :3, :3], local)
    origins = views[:, None, None, :3, 3].expand_as(directions)
    return origins, directions


@torch.no_grad()
def render_scene(views, height, width, seed, texture_scale=1.):
    origins, directions = camera_rays(views, height, width)
    return render_scene_rays(origins, directions, seed, texture_scale=texture_scale)


@torch.no_grad()
def render_scene_rays(origins, directions, seed, return_ids=False, texture_scale=1.):
    """Evaluate the same opaque scene for arbitrary rays; leading axes are free."""
    # A Lambertian background plane and three overlapping textured cards.
    textures = [(.75, .25, .18), (.15, .65, .3), (.2, .3, .8)]
    shift = (seed % 3-1)*1.7
    objects = [(-4., 3.+shift, 14.+shift, -7., 9., textures[2]),
               (0., -4.+shift, 7.+shift, -9., 6., textures[1]),
               (4., -13.+shift, 0.+shift, -4., 10., textures[0])]
    background_distance = (-10.-origins[..., 0])/directions[..., 0]
    background = origins+background_distance[..., None]*directions
    modulation = .025*torch.sin(background[..., 1]*.4+seed)*torch.cos(background[..., 2]*.4)
    color = (.91+modulation[..., None]).expand(*modulation.shape, 3).clone()
    nearest = background_distance.clone()
    ids = torch.zeros_like(nearest, dtype=torch.long)
    for number, (depth, y0, y1, z0, z1, base) in enumerate(objects, 1):
        distance = (depth-origins[..., 0])/directions[..., 0]
        point = origins+distance[..., None]*directions
        visible = (distance > 0)&(distance < nearest)&(point[..., 1] >= y0)&(point[..., 1] <= y1)
        visible &= (point[..., 2] >= z0)&(point[..., 2] <= z1)
        wave = torch.sin(point[..., 1]*(1.3+seed*.07)*texture_scale)*torch.cos(point[..., 2]*1.1*texture_scale)
        rgb = torch.tensor(base, device=origins.device)+.14*wave[..., None]
        color = torch.where(visible[..., None], rgb.clamp(.03, .97), color)
        nearest = torch.where(visible, distance, nearest)
        ids = torch.where(visible, number, ids)
    color = color.movedim(-1, -3).contiguous()
    return (color, ids) if return_ids else color


def analytic_case(seed, height, width, device, texture_scale=1., geometry_profile='ta'):
    _, screens = synthetic_geometry(height, width, device, profile=geometry_profile)
    # Eye baseline follows the head's horizontal direction, IPD = 6 cm.
    centres = [(70., -16., 4.), (85., 0., 0.), (105., 24., 9.), (55., 12., -5.)]
    midpoint = torch.tensor(centres[seed % len(centres)], device=device)
    head = look_at(midpoint)
    positions = [midpoint-3*head[:3, 0], midpoint+3*head[:3, 0]]
    views = torch.stack([look_at(p) for p in positions])
    neighbours, offsets = [], []
    for radius_cm in (.15, .6):
        for eye, view in enumerate(views):
            for dx, dy in [(-radius_cm, 0.), (radius_cm, 0.), (0., -radius_cm), (0., radius_cm)]:
                position = view[:3, 3]+dx*view[:3, 0]+dy*view[:3, 1]
                neighbours.append(look_at(position))
                offsets.append({'eye': eye, 'radius_cm': radius_cm, 'local_offset_cm': [dx, dy]})
    neighbour_views = torch.stack(neighbours)
    return {'name': f'analytic_{seed}', 'target': render_scene(views, height, width, seed, texture_scale),
            'views': views, 'screens': screens,
            'neighbour_views': neighbour_views,
            'neighbour_target': render_scene(neighbour_views, height, width, seed, texture_scale),
            'metadata': {'kind': 'analytic three-depth textured-card scene', 'seed': seed,
                'neighbours': offsets, 'neighbour_targets_used_for_optimization': False,
                'depths_cm': [4., 0., -4.], 'midpoint_cm': midpoint.cpu().tolist(),
                'texture_scale': texture_scale, 'geometry_profile': geometry_profile}}
